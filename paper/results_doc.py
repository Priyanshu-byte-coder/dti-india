def rd(*p):
    f = R.joinpath(*p)
    return pd.read_csv(f) if f.exists() else None


def stars(p):
    return "***" if p < 0.01 else "**" if p < 0.05 else "*" if p < 0.1 else ""


def lp(b, se=None, p=None):
    s = f"{100 * b:.1f}" + (stars(p) if p is not None else "")
    return s + (f" ({100 * se:.1f})" if se is not None else "")


def md(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def row(df, model, term="dti_std"):
    if df is None:
        return None
    r = df[(df["model"] == model) & (df["term"] == term)]
    return r.iloc[0] if len(r) else None


def cell(df, model, term="dti_std"):
    r = row(df, model, term)
    return "—" if r is None else lp(r["coef"], r["se"], r["p"])


