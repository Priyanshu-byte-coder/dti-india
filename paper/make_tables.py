"""Build the paper's results tables (Markdown) from a reports directory, so no number in
the paper is typed by hand.

    python paper/make_tables.py reports/econ_onet "O*NET-transferred DTI (preliminary)" paper/tables_onet.md
    python paper/make_tables.py reports/econ "NCO-LLM DTI" paper/tables_llm.md
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd


def stars(p):
    return "***" if p < 0.01 else "**" if p < 0.05 else "*" if p < 0.1 else ""


def cell(coef, se, p):
    return f"{coef:.3f}{stars(p)} ({se:.3f})"


def md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def read(d, name):
    p = d / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else None


def main(rep, label, out):
    d = Path(rep)
    parts = [f"# Results tables: {label}", "",
             f"Generated by `paper/make_tables.py` from `{rep}/`. Coefficients with clustered standard errors "
             "(by 3-digit occupation) in parentheses; * p<0.1, ** p<0.05, *** p<0.01. Dependent variable: log real "
             "hourly wage unless stated. DTI standardised across workers (1 SD).", ""]

    s = read(d, "sample_summary")
    if s is not None:
        t = s.assign(
            n=s["n"].map("{:,}".format), groups=s["n_occ_groups"],
            female=(100 * s["share_female"]).round(1), rural=(100 * s["share_rural"]).round(1),
            casual=(100 * s["share_casual"]).round(1), ln_wage=s["mean_ln_wage"].round(3),
        )[["round", "occ_system", "n", "groups", "female", "rural", "casual", "ln_wage"]]
        t.columns = ["Round", "NCO", "Workers", "Occ. groups", "% female", "% rural", "% casual", "Mean ln wage"]
        parts += ["## Table 1. Analysis sample (regular and casual wage earners, 15–64)", "", md(t),
                  f"\nTotal: {s['n'].sum():,} workers.", ""]

    b = read(d, "baseline")
    if b is not None:
        rows = []
        for m, g in b.groupby("model", sort=False):
            for r in g.itertuples():
                rows.append([m, r.term, cell(r.coef, r.se, r.p), f"{int(r.n):,}", int(r.n_clusters), f"{r.r2:.3f}"])
        t = pd.DataFrame(rows, columns=["Model", "Term", "Coef. (SE)", "N", "Clusters", "R²"])
        parts += ["## Table 2. Conditional digital occupational premium (RQ3)", "",
                  "M1: year-quarter FE. M2: + individual controls, education, social group, religion FE. "
                  "M3: + state and industry FE. M4 (preferred): + occupational division FE. M5: dimensions.", "",
                  md(t), ""]

    o = read(d, "oster")
    if o is not None:
        r = o.iloc[0]
        parts += ["## Table 3. Oster (2019) coefficient stability", "",
                  md(pd.DataFrame([[f"{r.beta_uncontrolled:.3f}", f"{r.r2_uncontrolled:.3f}", f"{r.beta_controlled:.3f}",
                                    f"{r.r2_controlled:.3f}", f"{r.rmax:.3f}", f"{r.delta_for_beta_0:.2f}", f"{r.beta_at_delta_1:.3f}"]],
                                  columns=["β (M1)", "R² (M1)", "β (M4)", "R² (M4)", "R_max = 1.3 R²", "δ for β = 0", "β at δ = 1"])),
                  "\nδ < 1 means selection on unobservables weaker than selection on observables would suffice "
                  "to explain the estimate away.", ""]

    rb = read(d, "robustness")
    if rb is not None:
        t = pd.DataFrame([[r.model, r.term, cell(r.coef, r.se, r.p), f"{int(r.n):,}"] for r in rb.itertuples()],
                         columns=["Specification", "Term", "Coef. (SE)", "N"])
        parts += ["## Table 4. Robustness", "", md(t),
                  "\nWild cluster bootstrap row: p-value from the bootstrap (999 replications).", ""]

    h = read(d, "heckman")
    if h is not None:
        t = pd.DataFrame([[r.model, r.term, cell(r.coef, r.se, r.p), f"{int(r.n):,}"] for r in h.itertuples()],
                         columns=["Sample", "Term", "Coef. (SE)", "N"])
        parts += ["## Table 5. Selection-corrected premium (Heckman two-step)", "",
                  f"Exclusion restrictions: {h['exclusion_restrictions'].iloc[0]}. Second-step SEs not corrected "
                  "for the generated regressor.", "", md(t), ""]

    q = read(d, "rif")
    cq = read(d, "cqr")
    if q is not None:
        t = pd.DataFrame({"Quantile": (100 * q["quantile"]).astype(int).astype(str),
                          "Unconditional (RIF)": [cell(r.coef, r.se, r.p) for r in q.itertuples()]})
        if cq is not None:
            t["Conditional (QR)"] = [cell(r.coef, r.se, r.p) for r in cq.itertuples()]
        parts += ["## Table 6. Premium across the wage distribution (RQ4)", "", md(t),
                  "\nConditional QR on a 100,000 random subsample with controls, education, year-quarter and division dummies.", ""]

    ox = read(d, "oaxaca")
    if ox is not None:
        t = ox[["component", "value"]].assign(value=ox["value"].round(4))
        t.columns = ["Component (men − women)", "Log points"]
        parts += ["## Table 7. Oaxaca–Blinder decomposition of the gender wage gap", "", md(t), ""]

    it = read(d, "interactions")
    if it is not None:
        t = pd.DataFrame([[r.model, r.term, cell(r.coef, r.se, r.p)] for r in it.itertuples()],
                         columns=["Specification", "Term", "Coef. (SE)"])
        parts += ["## Table 8. Heterogeneity: DTI × group interactions (RQ4)", "",
                  "Base groups: male, urban, up to primary education, age 25–34, regular employment. "
                  "Rows under 'occupation FE' identify interactions within 3-digit occupations.", "", md(t), ""]

    sg = read(d, "subgroups")
    if sg is not None:
        t = pd.DataFrame([[r.group_var, r.group_level, cell(r.coef, r.se, r.p), f"{int(r.n):,}"] for r in sg.itertuples()],
                         columns=["Group", "Level", "Coef. (SE)", "N"])
        parts += ["## Table 9. Premium by subgroup (M4 estimated separately)", "", md(t), ""]

    ate, blp, gate = read(d, "dml_ate"), read(d, "dml_blp"), read(d, "dml_gate")
    if ate is not None:
        a = ate.iloc[0]
        parts += ["## Table 10. Double/debiased machine learning (RQ4)", "",
                  f"Average partial effect: {a['coef']:.3f} (SE {a['std err']:.3f}), 95% CI [{a['2.5 %']:.3f}, {a['97.5 %']:.3f}], "
                  f"N = {int(a['n']):,} (random subsample).", ""]
        if blp is not None:
            se_col = next(c for c in blp.columns if "err" in c)
            p_col = next(c for c in blp.columns if c.startswith("P>"))
            t = pd.DataFrame([[r["term"], cell(r["coef"], r[se_col], r[p_col])] for _, r in blp.iterrows()],
                             columns=["Term", "BLP coef. (SE)"])
            parts += ["Best linear projection of the effect on pre-specified covariates:", "", md(t), ""]
        if gate is not None:
            t = gate.assign(ci=[f"[{lo:.3f}, {hi:.3f}]" for lo, hi in zip(gate["2.5 %"], gate["97.5 %"])])
            t = t[["dimension", "group", "effect", "ci", "n_group"]].assign(effect=t["effect"].round(3), n_group=t["n_group"].map("{:,}".format))
            t.columns = ["Dimension", "Group", "Effect", "95% CI", "N"]
            parts += ["Group average effects:", "", md(t), ""]

    Path(out).write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
